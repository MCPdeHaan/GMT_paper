#!/usr/bin/env python3
"""Write paper_v2_refs.bib, a BibTeX (natbib) projection of bibliography.bib.

bibliography.bib is maintained in biblatex format (date, journaltitle, @online,
@report, ids). This script converts the entries cited in paper_v2.tex so that
pdflatex + bibtex compile without biber. Run from writing/:
    python3 make_paper_bib.py
"""
import re

TYPE_MAP = {"online": "misc", "report": "techreport", "dataset": "misc"}
DROP = {"abstract", "file", "keywords", "langid", "urldate", "shorttitle", "shortjournal",
        "issn", "eprint", "eprinttype", "pubstate", "ids", "location", "subtitle", "version"}


def entries(text):
    for match in re.finditer(r"@(\w+)\{([^,\s]+),", text):
        depth, i = 1, match.end()
        while depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        yield match.group(1).lower(), match.group(2), text[match.end():i - 1]


def fields(body):
    out, i = {}, 0
    for match in re.finditer(r"(\w+)\s*=\s*\{", body):
        if match.start() < i:
            continue
        depth, j = 1, match.end()
        while depth:
            depth += {"{": 1, "}": -1}.get(body[j], 0)
            j += 1
        out[match.group(1).lower()] = body[match.end():j - 1]
        i = j
    return out


def convert(kind, key, f):
    kind = TYPE_MAP.get(kind, kind)
    if "date" in f:
        f.setdefault("year", f.pop("date")[:4])
    if "journaltitle" in f:
        f["journal"] = f.pop("journaltitle")
    if kind == "techreport":
        f.setdefault("institution", f.get("organization", ""))
    if kind == "misc":
        if f.get("type") == "SSRN Scholarly Paper":
            f["howpublished"] = "SSRN Working Paper"
        elif "organization" in f:
            f["howpublished"] = f["organization"]
        f.pop("type", None)
    f.pop("organization", None)
    if kind == "article" and "journal" not in f:
        kind = "misc"
    if "url" in f and "doi" in f:
        f.pop("url")
    if "url" in f:
        f["note"] = (f.get("note", "") + " " if f.get("note") else "") + "\\url{" + f.pop("url") + "}"
    if "doi" in f:
        f["note"] = (f.get("note", "") + " " if f.get("note") else "") + "doi:\\nolinkurl{" + f.pop("doi") + "}"
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in f.items() if k not in DROP and v)
    return f"@{kind}{{{key},\n{body}\n}}\n"


def main():
    tex = open("paper_v2.tex", encoding="utf-8").read()
    cited = set()
    for group in re.findall(r"\\cite[a-z]*\*?(?:\[[^\]]*\])*\{([^}]*)\}", tex):
        cited.update(k.strip() for k in group.split(","))
    out, found = [], set()
    for kind, key, body in entries(open("bibliography.bib", encoding="utf-8").read()):
        f = fields(body)
        for name in [key] + [a.strip() for a in f.get("ids", "").split(",") if a.strip()]:
            if name in cited:
                out.append(convert(kind, name, dict(f)))
                found.add(name)
    missing = sorted(cited - found)
    if missing:
        raise SystemExit("Citation keys missing from bibliography.bib: " + ", ".join(missing))
    header = "% Generated by make_paper_bib.py from bibliography.bib. Do not edit by hand.\n\n"
    open("paper_v2_refs.bib", "w", encoding="utf-8").write(header + "\n".join(out))
    print(f"Wrote {len(out)} entries to paper_v2_refs.bib")


if __name__ == "__main__":
    main()
